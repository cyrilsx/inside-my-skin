#!/usr/bin/env bash
# HealthHub local dev launcher: PostgreSQL + backend (Maven) + frontend (Vite) with one command.
#
#   ./scripts/dev.sh              # start everything, Ctrl+C stops all
#   ./scripts/dev.sh --down       # also stop the postgres container on exit
#   ./scripts/dev.sh --no-db      # skip docker compose (use your own DATABASE_URL)
#   ./scripts/dev.sh --build      # force a full backend rebuild first
#
# Local secrets are generated once into .dev-env (gitignored) and reused, so encrypted
# tokens/credentials survive restarts. Override any of them by exporting before running.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

DOWN=0 NO_DB=0 BUILD=0
for arg in "$@"; do
  case "$arg" in
    --down) DOWN=1 ;;
    --no-db) NO_DB=1 ;;
    --build) BUILD=1 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

log() { printf '\033[1;36m[dev.sh]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[dev.sh]\033[0m %s\n' "$*" >&2; exit 1; }

if ! command -v java >/dev/null 2>&1 && [ -n "${JAVA_HOME:-}" ] && [ -x "$JAVA_HOME/bin/java" ]; then
  export PATH="$JAVA_HOME/bin:$PATH"
fi
command -v java >/dev/null || die "java not found — install JDK 25 and set JAVA_HOME"
java -version 2>&1 | grep -q 'version "25' || log "warning: expected JDK 25, found: $(java -version 2>&1 | head -1)"
command -v node >/dev/null || die "node not found — install Node 22"
command -v docker >/dev/null || [ "$NO_DB" = 1 ] || die "docker not found — install Docker or use --no-db with your own DATABASE_URL"

# ---------------------------------------------------------------- local secrets
ENV_FILE="$ROOT/.dev-env"
gen_secret() { head -c 32 /dev/urandom | base64 | tr -d '\n'; }
if [ ! -f "$ENV_FILE" ]; then
  log "generating local dev secrets into .dev-env (gitignored)"
  {
    echo "# generated by scripts/dev.sh — local dev only, never commit"
    echo "POSTGRES_PASSWORD=$(gen_secret)"
    echo "JWT_SIGNING_KEY=$(gen_secret)"
    echo "TOKEN_ENCRYPTION_KEY=$(gen_secret)"
    echo "WEBHOOK_SECRET=$(gen_secret)"
  } > "$ENV_FILE"
fi
set -a; source "$ENV_FILE"; set +a
: "${POSTGRES_PASSWORD:?POSTGRES_PASSWORD missing in .dev-env}"
: "${JWT_SIGNING_KEY:?}"; : "${TOKEN_ENCRYPTION_KEY:?}"; : "${WEBHOOK_SECRET:?}"

mkdir -p "$ROOT/logs"
PIDS=()
cleanup() {
  log "stopping…"
  for pid in "${PIDS[@]:-}"; do kill "$pid" 2>/dev/null || true; done
  [ "$DOWN" = 1 ] && [ "$NO_DB" = 0 ] && docker compose -f infra/docker-compose.yml down || true
  wait 2>/dev/null || true
  log "bye"
}
trap cleanup EXIT INT TERM

# ---------------------------------------------------------------- postgres
if [ "$NO_DB" = 0 ]; then
  if [ -n "${DATABASE_URL:-}" ]; then
    log "DATABASE_URL is set — skipping docker compose, using $DATABASE_URL"
    NO_DB=1
  else
    log "starting postgres (infra/docker-compose.yml)…"
    docker compose -f infra/docker-compose.yml up -d postgres
    for i in $(seq 1 30); do
      if docker compose -f infra/docker-compose.yml exec -T postgres pg_isready -U "${POSTGRES_USER:-healthhub}" -d "${POSTGRES_DB:-healthhub}" >/dev/null 2>&1; then
        log "postgres is ready"
        break
      fi
      [ "$i" = 30 ] && die "postgres did not become ready in 30s"
      sleep 1
    done
    export DATABASE_URL="jdbc:postgresql://localhost:${POSTGRES_PORT:-5432}/${POSTGRES_DB:-healthhub}"
    export POSTGRES_USER="${POSTGRES_USER:-healthhub}"
  fi
fi
[ -n "${DATABASE_URL:?}" ] || die "DATABASE_URL must be set when using --no-db"

# ---------------------------------------------------------------- backend
if [ "$BUILD" = 1 ] || [ ! -d backend/app/target/classes ]; then
  log "building backend (./mvnw install -DskipTests)…"
  ./mvnw -q install -DskipTests
fi
log "starting backend on :8080 (logs/backend.log)…"
JWT_SIGNING_KEY="$JWT_SIGNING_KEY" TOKEN_ENCRYPTION_KEY="$TOKEN_ENCRYPTION_KEY" WEBHOOK_SECRET="$WEBHOOK_SECRET" \
  DATABASE_URL="$DATABASE_URL" POSTGRES_USER="${POSTGRES_USER:-healthhub}" POSTGRES_PASSWORD="$POSTGRES_PASSWORD" \
  ./mvnw -q -pl backend/app spring-boot:run > logs/backend.log 2>&1 &
PIDS+=($!)
for i in $(seq 1 60); do
  if grep -q "Started HealthHubApplication" logs/backend.log 2>/dev/null; then log "backend is up"; break; fi
  if grep -qE "Application run failed|BUILD FAILURE" logs/backend.log 2>/dev/null; then die "backend failed to start — see logs/backend.log"; fi
  [ "$i" = 60 ] && die "backend did not start in 60s — see logs/backend.log"
  sleep 2
done

# ---------------------------------------------------------------- frontend
log "starting frontend on :5173 (logs/frontend.log)…"
cd frontend
[ -d node_modules ] || npm install
npm run dev > "$ROOT/logs/frontend.log" 2>&1 &
PIDS+=($!)
cd "$ROOT"

log "ready:"
log "  dashboard  http://localhost:5173   (API proxied to :8080)"
log "  swagger    http://localhost:8080/swagger-ui"
log "  backend    http://localhost:8080  (logs/backend.log, logs/frontend.log)"
log "Ctrl+C to stop everything"
wait
